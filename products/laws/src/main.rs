//! `cargo run` prints LAWS.md (the generated ontology tables). `cargo run -- lock` prints interface.lock.
use sheaf_laws::*;

fn scope(s: Scope) -> String {
    match s {
        Scope::Root => "root".into(),
        Scope::Stage(o) => format!("{o:?}"),
        Scope::Edge(a, b) => format!("{a:?} → {b:?}"),
        Scope::Product(p, o) => format!("{p:?} · {o:?}"),
    }
}

fn tree(all: &[Law], id: &str, indent: usize, out: &mut String) {
    let l = all.iter().find(|l| l.id == id).unwrap();
    out.push_str(&format!("{}{} [{:?}] {}\n", "  ".repeat(indent), l.id, l.tier, scope(l.scope)));
    for c in all.iter().filter(|c| c.parent == Some(id)) { tree(all, c.id, indent + 1, out); }
}

fn main() {
    let all = laws();
    if std::env::args().nth(1).as_deref() == Some("lock") {
        // interface.lock skeleton: per stage, its signature and law ids. Proof hashes are filled by the Mac gate.
        println!("{{\n  \"format\": \"sheaf-products/interface-lock-v0\",\n  \"stages\": {{");
        for (i, op) in Op::ALL.iter().enumerate() {
            let (ins, out) = op.signature();
            let ids: Vec<String> = all.iter().filter(|l| matches!(l.scope, Scope::Stage(o) if o == *op) || matches!(l.scope, Scope::Product(_, o) if o == *op))
                .map(|l| format!("\"{}\"", l.id)).collect();
            println!("    \"{op:?}\": {{\"in\": {:?}, \"out\": \"{out:?}\", \"owner\": \"{:?}\", \"laws\": [{}], \"bend_proof_sha256\": null, \"haskell_props_sha256\": null}}{}",
                ins.iter().map(|c| format!("{c:?}")).collect::<Vec<_>>(), op.owner(), ids.join(", "), if i + 1 < Op::ALL.len() { "," } else { "" });
        }
        println!("  }}\n}}");
        return;
    }
    let mut o = String::new();
    o.push_str("# Law ontology — generated by `cargo run` in products/laws (do not edit by hand)\n\n");
    let n = |t: Tier| all.iter().filter(|l| l.tier == t).count();
    o.push_str(&format!("{} laws: {} Formal (Bend + Haskell), {} Types (Rust), {} CoreCited, {} Differential, {} Property.\n\n",
        all.len(), n(Tier::Formal), n(Tier::Types), n(Tier::CoreCited), n(Tier::Differential), n(Tier::Property)));
    o.push_str("## Tree (law → the laws that refine it)\n\n```\n");
    for g in all.iter().filter(|l| l.layer == Layer::Global) { tree(&all, g.id, 0, &mut o); }
    o.push_str("```\n\n## Pipeline (one composite; each stage many-in, one-out)\n\n| stage | in | out | owner |\n|---|---|---|---|\n");
    for op in Op::ALL { let (i, out) = op.signature(); o.push_str(&format!("| {op:?} | {} | {out:?} | {:?} |\n", i.iter().map(|c| format!("{c:?}")).collect::<Vec<_>>().join(", "), op.owner())); }
    for (title, layer) in [("L0 Global", Layer::Global), ("L1 Stage and interface", Layer::Stage), ("L2 Atom", Layer::Atom), ("L3 Product", Layer::Product)] {
        o.push_str(&format!("\n## {title}\n\n| id | where | tier | law | derives from | evidence |\n|---|---|---|---|---|---|\n"));
        for l in all.iter().filter(|l| l.layer == layer) {
            o.push_str(&format!("| {} | {} | {:?} | {} | {} | {} |\n", l.id, scope(l.scope), l.tier, l.statement, l.derives_from.join(", "), l.evidence.join(", ")));
        }
    }
    o.push_str("\n## How each layer becomes code (Touchstone atom pipeline)\n\n| layer | proved in | enforced in | shipped in | gate |\n|---|---|---|---|---|\n");
    o.push_str("| L0 Global | composition of L1 (derivations above) | weakest-link tier check (tests/ontology.rs) | receipts + join (sheaf-kit) | every step below |\n");
    o.push_str("| L1 Stage / interface | Bend LAWS.bend (Formal leaves) | Haskell Laws.hs, same ids | one Rust module per stage | bridge tables A, A', B |\n");
    o.push_str("| L2 Atom | Bend PROOF.bend (+ --verdict) | Haskell, exhaustive small domain | Rust fn + same-id test | mutation L0 (Bend), L2 (cargo-mutants) |\n");
    o.push_str("| L3 Product | Bend instance of its parent atom | Haskell | per-product crate | product fixtures + differential vs core binary |\n");
    o.push_str("\n## Holes found by deriving each global law from its parts\n\n");
    for (h, why) in holes() { o.push_str(&format!("- **{h}.** {why}\n")); }
    print!("{o}");
}
