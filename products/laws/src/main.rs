//! `cargo run` prints LAWS.md (the generated ontology tables). `cargo run -- lock` prints interface.lock.
use sheaf_laws::*;

fn scope(s: Scope) -> String {
    match s {
        Scope::Root => "root".into(),
        Scope::Stage(o) => format!("{o:?}"),
        Scope::Edge(a, b) => format!("{a:?} → {b:?}"),
        Scope::Product(p, o) => format!("{p:?} · {o:?}"),
    }
}

fn tree(all: &[Law], id: &str, indent: usize, out: &mut String) {
    let l = all.iter().find(|l| l.id == id).unwrap();
    out.push_str(&format!("{}{} [{:?}] {}\n", "  ".repeat(indent), l.id, l.tier, scope(l.scope)));
    for c in all.iter().filter(|c| c.parent == Some(id)) { tree(all, c.id, indent + 1, out); }
}

fn main() {
    let all = laws();
    if std::env::args().nth(1).as_deref() == Some("selfsheaf") {
        let dir = std::env::args().nth(2).expect("selfsheaf <out-dir>");
        std::fs::create_dir_all(&dir).unwrap();
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
        let rust_tests = std::fs::read_to_string(root.join("../kit/tests/laws.rs")).unwrap();
        let laws_bend = std::fs::read_to_string(root.join("../bend/LAWS.bend")).unwrap();
        let g = sheaf_laws::selfsheaf::coverage();
        let pins: Vec<(String, f64)> = all.iter().filter(|l| sheaf_laws::selfsheaf::is_leaf(&all, l))
            .map(|l| (l.id.to_string(), sheaf_laws::selfsheaf::evidence_level(l, &rust_tests, &laws_bend))).collect();
        std::fs::write(format!("{dir}/coverage.spec.json"), g.spec_json(None)).unwrap();
        std::fs::write(format!("{dir}/coverage.boundary.json"), sheaf_laws::selfsheaf::boundary_json(&pins)).unwrap();
        let (c, cp) = sheaf_laws::selfsheaf::contradiction();
        let adopted = |n: &str| if n.starts_with("v1.") { 1.0 } else { 1.0 };
        std::fs::write(format!("{dir}/contradiction.spec.json"), c.spec_json(Some(&adopted))).unwrap();
        std::fs::write(format!("{dir}/contradiction.boundary.json"), sheaf_laws::selfsheaf::boundary_json(&cp)).unwrap();
        eprintln!("coverage: {} nodes, {} edges, {} leaf pins; contradiction: {} nodes, {} edges", g.nodes.len(), g.edges.len(), pins.len(), c.nodes.len(), c.edges.len());
        return;
    }
    if std::env::args().nth(1).as_deref() == Some("lock") {
        // interface.lock skeleton: per stage, its signature and law ids. Proof hashes are filled by the Mac gate.
        println!("{{\n  \"format\": \"sheaf-products/interface-lock-v1\",\n  \"auto_approve\": \"refused while any proof or bridge hash is null\",\n  \"stages\": {{");
        for (i, op) in Op::ALL.iter().enumerate() {
            let (ins, out) = op.signature();
            let ids: Vec<String> = all.iter().filter(|l| matches!(l.scope, Scope::Stage(o) if o == *op) || matches!(l.scope, Scope::Product(_, o) if o == *op))
                .map(|l| format!("\"{}\"", l.id)).collect();
            println!("    \"{op:?}\": {{\"in\": {:?}, \"out\": \"{out:?}\", \"owner\": \"{:?}\", \"laws\": [{}], \"type_fnv64\": \"{:016x}\", \"effect\": \"{}\", \"bend_proof_sha256\": null, \"haskell_props_sha256\": null, \"bridge_sha256\": null}}{}",
                ins.iter().map(|c| format!("{c:?}")).collect::<Vec<_>>(), op.owner(), ids.join(", "), fnv(&format!("{op:?}{ins:?}{out:?}")), op.effect(), if i + 1 < Op::ALL.len() { "," } else { "" });
        }
        println!("  }}\n}}");
        return;
    }
    let mut o = String::new();
    o.push_str("# Law ontology — generated by `cargo run` in products/laws (do not edit by hand)\n\n");
    let n = |t: Tier| all.iter().filter(|l| l.tier == t).count();
    o.push_str(&format!("{} laws: {} Formal (Bend + Haskell), {} Types (Rust), {} CoreCited, {} Differential, {} Property.\n\n",
        all.len(), n(Tier::Formal), n(Tier::Types), n(Tier::CoreCited), n(Tier::Differential), n(Tier::Property)));
    o.push_str("## Tree (law → the laws that refine it)\n\n```\n");
    for g in all.iter().filter(|l| l.layer == Layer::Global) { tree(&all, g.id, 0, &mut o); }
    o.push_str("```\n\n## Pipeline (one composite; each stage many-in, one-out)\n\n| stage | in | out | owner |\n|---|---|---|---|\n");
    for op in Op::ALL { let (i, out) = op.signature(); o.push_str(&format!("| {op:?} | {} | {out:?} | {:?} |\n", i.iter().map(|c| format!("{c:?}")).collect::<Vec<_>>().join(", "), op.owner())); }
    for (title, layer) in [("L0 Global", Layer::Global), ("L1 Stage and interface", Layer::Stage), ("L2 Atom", Layer::Atom), ("L3 Product", Layer::Product)] {
        o.push_str(&format!("\n## {title}\n\n| id | where | tier | law | derives from | evidence |\n|---|---|---|---|---|---|\n"));
        for l in all.iter().filter(|l| l.layer == layer) {
            o.push_str(&format!("| {} | {} | {:?} | {} | {} | {} |\n", l.id, scope(l.scope), l.tier, l.statement, l.derives_from.join(", "), l.evidence.join(", ")));
        }
    }
    o.push_str("\n## How each layer becomes code (Touchstone atom pipeline)\n\n| layer | proved in | enforced in | shipped in | gate |\n|---|---|---|---|---|\n");
    o.push_str("| L0 Global | composition of L1 (derivations above) | weakest-link tier check (tests/ontology.rs) | receipts + join (sheaf-kit) | every step below |\n");
    o.push_str("| L1 Stage / interface | Bend LAWS.bend (Formal leaves) | Haskell Laws.hs, same ids | one Rust module per stage | bridge tables A, A', B |\n");
    o.push_str("| L2 Atom | Bend PROOF.bend (+ --verdict) | Haskell, exhaustive small domain | Rust fn + same-id test | mutation L0 (Bend), L2 (cargo-mutants) |\n");
    o.push_str("| L3 Product | Bend instance of its parent atom | Haskell | per-product crate | product fixtures + differential vs core binary |\n");
    o.push_str("\n## Status: holes (open questions or known violations; they propagate to every law derived from them)\n\n| id | layer | law |\n|---|---|---|\n");
    for l in all.iter().filter(|l| effective_status(&all, l.id) == Status::Hole) { o.push_str(&format!("| {} | {:?} | {} |\n", l.id, l.layer, l.statement)); }
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
    let rd = |p: &str| std::fs::read_to_string(root.join(p)).unwrap_or_default();
    let (lb, pb, hs, rs) = (rd("bend/LAWS.bend"), rd("bend/PROOF.bend"), rd("haskell/Laws.hs"), rd("kit/tests/laws.rs"));
    o.push_str("\n## Formal leaves: backing at every layer (LAWS.bend law + PROOF.bend def + Haskell property + Rust test, same id)\n\n| id | backed | cites |\n|---|---|---|\n");
    for l in all.iter().filter(|l| l.tier == Tier::Formal && l.derives_from.is_empty()) {
        let (b, n) = formal_backing(l, &lb, &pb, &hs, &rs);
        o.push_str(&format!("| {} | {} of {} | {} |\n", l.id, b, n, l.evidence.join(", ")));
    }
    o.push_str("\nA Formal leaf with backing below its cite count is a planned proof, not a proof. 'Proved' is said only after the Mac gate records ALL PROOFS CHECK and --verdict for it.\n");
    o.push_str("\n## Spec capabilities (coverage fixture: src/capabilities.rs)\n\n| id | capability | spec | stages | laws |\n|---|---|---|---|---|\n");
    for c in sheaf_laws::capabilities::capabilities() {
        match c.cover {
            sheaf_laws::capabilities::Cover::Laws(ops, ls) => o.push_str(&format!("| {} | {} | {} | {} | {} |\n", c.id, c.what, c.spec, ops.iter().map(|o| format!("{o:?}")).collect::<Vec<_>>().join(", "), ls.join(", "))),
            sheaf_laws::capabilities::Cover::Deferred(why) => o.push_str(&format!("| {} | {} | {} | deferred | {} |\n", c.id, c.what, c.spec, why)),
        }
    }
    print!("{o}");
}

/// FNV-1a 64 of a stage's signature text: a cheap, dependency-free type fingerprint for interface.lock.
fn fnv(s: &str) -> u64 { s.bytes().fold(0xcbf29ce484222325u64, |h, b| (h ^ b as u64).wrapping_mul(0x100000001b3)) }
